// Convierte el JSON categorizado de Claude a un .xlsx descargable (browser)

import * as XLSX from 'xlsx';

export interface StatementTransaction {
  date: string;
  description: string;
  amount: number;
  type: 'credit' | 'debit';
  category: string;
  taxCategory: string;
  notes?: string;
}

interface CategorySummary {
  total: number;
  count: number;
  transactions: string[];
}

export interface StatementData {
  bank: string;
  accountHolder: string;
  accountNumber: string;
  statementPeriod: string;
  openingBalance: number;
  closingBalance: number;
  totalDeposits: number;
  totalWithdrawals: number;
  transactionCount: number;
  transactions: StatementTransaction[];
  summary: {
    byCategory: Record<string, CategorySummary>;
  };
}

export function generateExcel(
  data: StatementData,
  clientName: string,
  taxYear: string,
  entityType: string,
): Uint8Array {
  const wb = XLSX.utils.book_new();

  const txRows = [
    ['Date', 'Description', 'Amount', 'Type', 'Category', 'Tax Category (IRS)', 'Notes'],
    ...data.transactions.map((t) => [
      t.date,
      t.description,
      t.type === 'debit' ? -Math.abs(t.amount) : Math.abs(t.amount),
      t.type === 'credit' ? 'INCOME' : 'EXPENSE',
      t.category,
      t.taxCategory,
      t.notes || '',
    ]),
  ];

  const wsTx = XLSX.utils.aoa_to_sheet(txRows);
  wsTx['!cols'] = [
    { wch: 12 },
    { wch: 45 },
    { wch: 14 },
    { wch: 10 },
    { wch: 28 },
    { wch: 25 },
    { wch: 30 },
  ];
  XLSX.utils.book_append_sheet(wb, wsTx, 'Transactions');

  const summaryRows: (string | number)[][] = [
    [`${clientName} — ${entityType} — Tax Year ${taxYear}`],
    [`Bank: ${data.bank} | Account: ***${data.accountNumber}`],
    [`Period: ${data.statementPeriod}`],
    [],
    ['CATEGORY SUMMARY', '', '', ''],
    ['Category', '# Transactions', 'Total Amount', 'Tax Deductible?'],
  ];

  const nonDeductible = [
    'Personal (no deductible)',
    'Transfers',
    'Credit Card Payments',
    'Owner Draws / Distributions',
    'Loan Payments',
  ];

  let totalDeductible = 0;
  let totalNonDeductible = 0;

  Object.entries(data.summary?.byCategory || {}).forEach(([cat, val]) => {
    const isDeductible = !nonDeductible.includes(cat);
    const total = Number(val.total) || 0;
    if (isDeductible && total < 0) totalDeductible += Math.abs(total);
    else totalNonDeductible += Math.abs(total);
    summaryRows.push([cat, val.count, total, isDeductible ? '✓ Yes' : '✗ No']);
  });

  summaryRows.push(
    [],
    ['TOTALS', '', '', ''],
    ['Opening Balance', '', data.openingBalance, ''],
    ['Closing Balance', '', data.closingBalance, ''],
    ['Total Deposits (Credits)', '', data.totalDeposits, ''],
    ['Total Withdrawals (Debits)', '', -Math.abs(data.totalWithdrawals), ''],
    [],
    ['Estimated Deductible Expenses', '', -totalDeductible, ''],
    ['Non-Deductible / Transfers', '', -totalNonDeductible, ''],
    [],
    [`Generated by Quivo | Client: ${clientName} | ${new Date().toLocaleDateString()}`],
  );

  const wsSummary = XLSX.utils.aoa_to_sheet(summaryRows);
  wsSummary['!cols'] = [{ wch: 35 }, { wch: 16 }, { wch: 18 }, { wch: 16 }];
  XLSX.utils.book_append_sheet(wb, wsSummary, 'Summary');

  const incomeRows = [
    ['Date', 'Description', 'Amount', 'Tax Category', 'Notes'],
    ...data.transactions
      .filter((t) => t.type === 'credit')
      .map((t) => [t.date, t.description, Math.abs(t.amount), t.taxCategory, t.notes || '']),
  ];
  const wsIncome = XLSX.utils.aoa_to_sheet(incomeRows);
  wsIncome['!cols'] = [{ wch: 12 }, { wch: 45 }, { wch: 14 }, { wch: 25 }, { wch: 30 }];
  XLSX.utils.book_append_sheet(wb, wsIncome, 'Income');

  const expenseRows = [
    ['Date', 'Description', 'Amount', 'Category', 'Tax Category', 'Notes'],
    ...data.transactions
      .filter((t) => t.type === 'debit')
      .map((t) => [
        t.date,
        t.description,
        -Math.abs(t.amount),
        t.category,
        t.taxCategory,
        t.notes || '',
      ]),
  ];
  const wsExpenses = XLSX.utils.aoa_to_sheet(expenseRows);
  wsExpenses['!cols'] = [
    { wch: 12 },
    { wch: 45 },
    { wch: 14 },
    { wch: 28 },
    { wch: 25 },
    { wch: 30 },
  ];
  XLSX.utils.book_append_sheet(wb, wsExpenses, 'Expenses');

  const buf = XLSX.write(wb, { type: 'array', bookType: 'xlsx' }) as ArrayBuffer;
  return new Uint8Array(buf);
}
